"""Academic report generation (Markdown, stdlib only)."""
from __future__ import annotations

from datetime import date, timedelta

from scholaros.config import REPORT_TITLE
from scholaros.services.deadlines import list_upcoming
from scholaros.services.gpa import compute_student_gpa
from scholaros.services.scheduler import generate_study_schedule
from scholaros.services.risk import get_course_risk
from scholaros.storage.migrations import get_connection
from scholaros.storage.repositories import CourseRepository


def generate_report(student_id: str, term_id: str | None = None) -> str:
    """Generate a Markdown academic report for a student."""
    gpa_result = compute_student_gpa(student_id, term_id=term_id)
    deadlines = list_upcoming(student_id)
    conn = get_connection()
    try:
        courses = CourseRepository(conn).list_all()
        if term_id:
            courses = [c for c in courses if c.term_id == term_id]
    finally:
        conn.close()

    lines: list[str] = [
        f"# {REPORT_TITLE}",
        "",
        f"**Student:** {student_id}",
        f"**Term:** {term_id or 'all terms'}",
        f"**Generated:** {date.today().isoformat()}",
        "",
        "## GPA Summary",
        "",
        f"- **GPA:** {gpa_result['gpa']}",
        f"- **Total Credits:** {gpa_result['total_credits']}",
        "",
        "## Course Risk",
        "",
        "| Course | Risk | Avg | Trend | Recommendation |",
        "|--------|------|-----|-------|----------------|",
    ]
    for c in courses:
        try:
            r = get_course_risk(c.id)
            lines.append(
                f"| {c.code} — {c.name} | {r.risk_level} | "
                f"{r.current_avg} | {r.trend} | {r.recommendation} |"
            )
        except ValueError:
            lines.append(f"| {c.code} — {c.name} | — | — | — | no data |")

    lines += ["", "## Upcoming Deadlines", ""]
    if deadlines:
        lines += [
            "| Assignment | Course | Due Date | Days Left |",
            "|------------|--------|----------|-----------|",
        ]
        for d in deadlines:
            lines.append(
                f"| {d.assignment_name} | {d.course_name} | "
                f"{d.due_date.isoformat()} | {d.days_left} |"
            )
    else:
        lines.append("No upcoming deadlines.")

    lines += ["", "## Study Schedule (next 14 days)", ""]
    today = date.today()
    blocks = generate_study_schedule(today, today + timedelta(days=14))
    if blocks:
        lines += [
            "| Date | Course | Topic | Priority |",
            "|------|--------|-------|----------|",
        ]
        for b in blocks:
            lines.append(
                f"| {b.date} | {b.course_name} | {b.topic} | {b.priority} |"
            )
    else:
        lines.append("No study blocks scheduled.")

    lines += ["", "---", "*Generated by ScholarOS*"]
    return "\n".join(lines) + "\n"